import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { parseEnv } from 'node:util'
import { randomUUID } from 'node:crypto'
import { createClient } from '@supabase/supabase-js'

// Local-only integration test. Uses public credentials, never an admin key.
// Test accounts and their captured emails remain available for inspection.
const env = parseEnv(await readFile('.env.local', 'utf8'))
const url = env.VITE_SUPABASE_URL
const key = env.VITE_SUPABASE_PUBLISHABLE_KEY
assert.equal(url, 'http://127.0.0.1:54321', 'This test only runs against the local CLI stack.')
assert.ok(key?.startsWith('sb_publishable_'), 'Use the local publishable key generated by the CLI.')
const run = 'auth-test-' + randomUUID().slice(0, 8)
const password = randomUUID() + 'aA1!'
const newPassword = randomUUID() + 'bB2!'
function client(storage = new Map()) {
  return createClient(url, key, { auth: {
    flowType: 'pkce', persistSession: true, autoRefreshToken: false, detectSessionInUrl: false,
    storage: { getItem: (k) => storage.get(k) ?? null, setItem: (k, v) => { storage.set(k, v) }, removeItem: (k) => { storage.delete(k) } },
  } })
}
function check(result, label) { assert.equal(result.error, null, label); return result.data }
const consumed = new Set()
async function emailLink(email) {
  for (let attempt = 0; attempt < 20; attempt++) {
    const inbox = await fetch('http://127.0.0.1:54324/api/v1/messages').then((r) => r.json())
    const message = inbox.messages?.find((m) => !consumed.has(m.ID) && m.To.some((to) => to.Address === email))
    if (message) {
      consumed.add(message.ID)
      const body = await fetch('http://127.0.0.1:54324/api/v1/message/' + message.ID).then((r) => r.json())
      const link = body.HTML.match(/href="([^"]+)"/)?.[1]?.replaceAll('&amp;', '&')
      assert.ok(link, 'Verification email contains a link')
      const parsed = new URL(link)
      assert.equal(parsed.origin, url, 'Only follow links to this local Supabase instance')
      return parsed.href
    }
    await new Promise((resolve) => setTimeout(resolve, 500))
  }
  throw new Error('Timed out waiting for local verification email')
}
async function exchangeEmail(authClient, email, recovery = false) {
  const response = await fetch(await emailLink(email), { redirect: 'manual' })
  const target = new URL(response.headers.get('location'))
  assert.equal(target.origin, 'http://127.0.0.1:5173', 'Auth redirect uses the frontend origin')
  assert.equal(target.pathname, '/auth/callback')
  if (recovery) assert.equal(target.searchParams.get('mode'), 'recovery')
  assert.equal(target.searchParams.get('invite'), 'integration-context', 'Invitation context survives email redirects')
  const code = target.searchParams.get('code')
  assert.ok(code, 'Email verification returns a PKCE code')
  const data = check(await authClient.auth.exchangeCodeForSession(code), 'PKCE exchange succeeds')
  assert.ok(data.user.email_confirmed_at, 'Email is verified')
  assert.ok((await authClient.auth.exchangeCodeForSession(code)).error, 'Reused codes fail')
  return data.user
}
const callback = 'http://127.0.0.1:5173/auth/callback?next=%2Fapp&invite=integration-context'
const storageA = new Map()
const a = client(storageA)
const b = client()
const emailA = run + '-a@example.test'
const emailB = run + '-b@example.test'
for (const [c, email, name] of [[a, emailA, 'Auth Test A'], [b, emailB, 'Auth Test B']]) {
  const signup = check(await c.auth.signUp({ email, password, options: { data: { name }, emailRedirectTo: callback } }), 'Registration succeeds')
  assert.equal(signup.session, null, 'Signup requires email verification')
  const login = await c.auth.signInWithPassword({ email, password })
  assert.equal(login.error?.code, 'email_not_confirmed', 'Unverified login is rejected')
}
const userA = await exchangeEmail(a, emailA)
const userB = await exchangeEmail(b, emailB)
console.log('PASS registration, mandatory verification, PKCE callback, replay rejection, invitation context')

const own = check(await a.from('profiles').select('*').eq('id', userA.id).single(), 'Own profile is readable')
assert.equal(own.name, 'Auth Test A', 'Signup trigger creates the profile')
assert.equal(check(await a.from('profiles').select('*').eq('id', userB.id), 'Cross-user select uses RLS').length, 0)
assert.equal(check(await a.from('profiles').update({ name: 'Unauthorized' }).eq('id', userB.id).select(), 'Cross-user update uses RLS').length, 0)
assert.equal(check(await b.from('profiles').select('name').eq('id', userB.id).single(), 'Other user profile is intact').name, 'Auth Test B')
assert.ok((await client().from('profiles').select('*')).error, 'Anonymous profile access is denied')
assert.ok((await a.from('profiles').insert({ id: randomUUID(), name: 'Unauthorized' })).error, 'Client profile insertion is denied')
assert.ok((await a.from('profiles').delete().eq('id', userA.id)).error, 'Client profile deletion is denied')
check(await a.from('profiles').update({ name: 'Auth Test A Updated' }).eq('id', userA.id), 'Own profile update succeeds')
console.log('PASS profile trigger, owner-only reads/updates, anonymous denial, insert/delete denial')

const restored = client(storageA)
assert.equal(check(await restored.auth.getUser(), 'Persisted session is valid').user.id, userA.id)
check(await restored.auth.refreshSession(), 'Refresh succeeds')
check(await restored.auth.signOut(), 'Logout succeeds')
assert.equal(check(await restored.auth.getSession(), 'Session lookup succeeds').session, null)
assert.ok((await restored.auth.signInWithPassword({ email: emailA, password: 'wrong-password' })).error, 'Wrong password rejected')
check(await restored.auth.signInWithPassword({ email: emailA, password }), 'Verified login succeeds')
check(await restored.auth.signOut(), 'Logout before recovery succeeds')
check(await restored.auth.resetPasswordForEmail(emailA, { redirectTo: callback + '&mode=recovery' }), 'Recovery request succeeds')
await exchangeEmail(restored, emailA, true)
check(await restored.auth.updateUser({ password: newPassword }), 'Password update succeeds')
check(await restored.auth.signOut(), 'Logout after recovery succeeds')
assert.ok((await restored.auth.signInWithPassword({ email: emailA, password })).error, 'Old password rejected')
check(await restored.auth.signInWithPassword({ email: emailA, password: newPassword }), 'New password accepted')
await restored.auth.signOut()
await b.auth.signOut()
console.log('PASS session persistence, refresh, logout, login errors, recovery, password replacement')
console.log('Local test accounts retained for inspection: ' + run + '-{a,b}@example.test')
